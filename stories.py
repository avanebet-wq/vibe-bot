def is_enabled(cid):
    return bool(get_setting(cid, "stories_enabled", True))


def set_enabled(cid, value):
    set_setting(cid, "stories_enabled", value)


def random_story():
    return random.choice(STORIES)


def cmd_tell_story(message):
    bot.reply_to(message, "📖 " + random_story())


def cmd_stories_on(message):
    set_enabled(message.chat.id, True)
    bot.reply_to(message, "📚 Хорошо, теперь буду иногда травить истории в чате.")


def cmd_stories_off(message):
    set_enabled(message.chat.id, False)
    bot.reply_to(message, "🤐 Ладно, историй больше не будет — только по запросу «Лиза, расскажи историю».")


def maybe_autotell(message, chance):
    """Небольшой шанс, что Лиза сама вставит историю в обычный разговор."""
    import random as _r
    if not is_enabled(message.chat.id):
        return False
    if _r.random() < chance:
        bot.send_message(message.chat.id, "📖 Кстати, вспомнила...\n\n" + random_story())
        return True
    return False
